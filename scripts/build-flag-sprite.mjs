/**
 * Builds public/flags.webp and lib/flag-sprite.ts from the flag SVGs.
 *
 * Why a sprite and not 195 files: opening the nationality list used to fire a
 * request per visible flag, and the SVG set is 1.2MB because a handful of
 * flags carry detailed coats of arms. At the 21x16 the UI actually draws, a
 * 3x raster is indistinguishable and the whole set is one small request that
 * caches once.
 *
 *   node scripts/build-flag-sprite.mjs  (needs the SVGs in scripts/flag-src/)
 *
 * The SVGs come from flag-icons (MIT). They are not kept in the repo; only
 * the generated sprite is.
 */
import fs from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

const SRC = path.join(import.meta.dirname, 'flag-src')
const SPRITE = path.join(import.meta.dirname, '..', 'public', 'flags.webp')
const MAP = path.join(import.meta.dirname, '..', 'lib', 'flag-sprite.ts')

// 3x the 21x16 the UI draws, so the sprite survives a high-DPI screen
const CELL_W = 63
const CELL_H = 48
const COLS = 14

const codes = fs
  .readdirSync(SRC)
  .filter((f) => f.endsWith('.svg'))
  .map((f) => f.replace('.svg', ''))
  .sort()

const rows = Math.ceil(codes.length / COLS)

const tiles = await Promise.all(
  codes.map(async (code, i) => ({
    input: await sharp(path.join(SRC, `${code}.svg`))
      .resize(CELL_W, CELL_H, { fit: 'fill' })
      .png()
      .toBuffer(),
    left: (i % COLS) * CELL_W,
    top: Math.floor(i / COLS) * CELL_H,
  })),
)

await sharp({
  create: {
    width: COLS * CELL_W,
    height: rows * CELL_H,
    channels: 4,
    background: { r: 0, g: 0, b: 0, alpha: 0 },
  },
})
  .composite(tiles)
  .webp({ quality: 96 })
  .toFile(SPRITE)

const entries = codes
  .map((code, i) => `  ${code.toUpperCase()}: [${i % COLS}, ${Math.floor(i / COLS)}],`)
  .join('\n')

fs.writeFileSync(
  MAP,
  `/**
 * Generated by scripts/build-flag-sprite.mjs — do not edit by hand.
 *
 * Each ISO code maps to its [column, row] in public/flags.webp. The CSS turns
 * that into a background-position; see .flag in globals.css.
 */

export const FLAG_COLS = ${COLS}
export const FLAG_ROWS = ${rows}

export const FLAG_CELL: Record<string, [number, number]> = {
${entries}
}
`,
)

const bytes = fs.statSync(SPRITE).size
console.log(
  `${codes.length} flags -> ${COLS}x${rows} sprite, ` +
    `${COLS * CELL_W}x${rows * CELL_H}px, ${(bytes / 1024).toFixed(0)}KB`,
)
